export function currentLang(): Lang {
  const s = loadSettings();
  return s.language === 'en' ? 'en' : 'zh';
}

export function setLang(l: Lang): void {
  const s: AppSettings = { ...loadSettings(), language: l };
  saveSettings(s);
}

export function t(key: string): string {
  const e = D[key];
  if (!e) return key;
  return currentLang() === 'en' ? e.en : e.zh;
}

/** Replace text by [data-i18n] and title by [data-i18n-title]. */
export function applyStatic(root: ParentNode = document): void {
  const l = currentLang();
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((el) => {
    const e = D[el.getAttribute('data-i18n') as string];
    if (e) el.textContent = l === 'en' ? e.en : e.zh;
  });
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((el) => {
    const e = D[el.getAttribute('data-i18n-title') as string];
    if (e) el.title = l === 'en' ? e.en : e.zh;
  });
}
